"""Build the synchronous browser catalogue from its JSON source."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def build():
    products = json.loads((ROOT / 'static/content/catalogue.json').read_text())
    ids = [product['id'] for product in products]
    if len(set(ids)) != len(ids):
        raise ValueError('Duplicate catalogue product IDs')
    for product in products:
        paths = [product['image']] + [view['image'] for view in product.get('gallery', [])]
        for path in paths:
            if not (ROOT / 'static' / path).is_file():
                raise ValueError(f'Missing catalogue image: {path}')
    data = json.dumps(products, indent=2, ensure_ascii=False)
    result = '''/* Generated by scripts/build_catalogue.py; edit static/content/catalogue.json. */
(function () {
  'use strict';
  const base = (window.CW_STATIC || '/static/').replace(/\\/?$/, '/');
  const url = path => /^(https?:)?\\//.test(path) ? path : base + path;
  const products = ''' + data + ''';
  window.COMEIIN_PRODUCTS = products.map(product => ({
    ...product,
    image: url(product.image),
    gallery: (product.gallery || []).map(view => ({ ...view, image: url(view.image) })),
  }));
})();
'''
    (ROOT / 'static/js/catalogue.js').write_text(result)


if __name__ == '__main__':
    build()
